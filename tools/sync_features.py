#!/usr/bin/env python3
"""Copies the feature copy of the landing page out of the App Store listing and the screenshot
headlines of kajet-ios, so the site says the same thing in every language without a second round
of translating. Writes tools/features_data.py (committed).

Usage:  python3 tools/sync_features.py [../kajet-ios]
"""
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
IOS = Path(sys.argv[1] if len(sys.argv) > 1 else HERE.parent.parent / "kajet-ios").resolve()
# site code -> fastlane metadata folder and screenshot-framing language key
LANGS = {"pl": ("pl", "pl"), "en": ("en-US", "en-US"), "de": ("de-DE", "de-DE"), "fr": ("fr-FR", "fr-FR"),
         "es": ("es-ES", "es-ES"), "it": ("it", "it"), "ja": ("ja", "ja"), "zh": ("zh-Hans", "zh-Hans"),
         "sv": ("sv", "sv"), "no": ("no", "no"), "cs": ("cs", "cs"), "sk": ("sk", "sk"), "pt": ("pt-PT", "pt-PT")}

spec = importlib.util.spec_from_file_location("frame", IOS / "scripts/frame_screenshots.py")
frame = importlib.util.module_from_spec(spec)
spec.loader.exec_module(frame)

out = {"scenes": [s[0] for s in frame.SCENES], "colors": {s[0]: [s[1], s[2]] for s in frame.SCENES}, "langs": {}}
for code, (meta, key) in LANGS.items():
    text = (IOS / "fastlane/metadata" / meta / "description.txt").read_text(encoding="utf-8")
    parts = [p.strip("\n") for p in text.strip().split("\n\n")]
    sections = []
    for part in parts[1:]:
        lines = part.split("\n")
        bullets = [l[1:].strip() for l in lines[1:] if l[:1] in ("•", "・")]
        if bullets:
            sections.append([lines[0].strip(), bullets])
    assert len(sections) == 10, (code, len(sections))
    out["langs"][code] = {
        "intro": parts[0],
        "sections": sections,
        "headlines": [" ".join(s[3][key]) for s in frame.SCENES],
    }
(HERE / "features_data.py").write_text(
    "# -*- coding: utf-8 -*-\n# Generated by tools/sync_features.py — do not edit.\nDATA = "
    + json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print("features_data.py:", len(out["langs"]), "languages")
